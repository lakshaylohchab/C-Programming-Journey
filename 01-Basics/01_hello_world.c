// File: 01_hello_world.c
// Purpose: Print Hello World and demonstrate basic escape sequences (\n and \t)

#include <stdio.h>

int main() {
    printf("Hello, World!\n");
    printf("Welcome to my C Programming Journey.\n\n");

    // Demonstrating tab (\t) and newline (\n) formatting
    printf("Folder\t\t: 01-Basics\n");
    printf("Language\t: C (GCC Compiler)\n");
    printf("Status\t\t: First program running successfully!\n");

    return 0;
}
